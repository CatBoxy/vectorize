#!/usr/bin/env bash
# Fetch openly licensed SVG sources into corpus/src/{bw,color}/.
#   bw    : Simple Icons (CC0) + Font Awesome Free solid (CC BY 4.0), monochrome
#   color : OpenMoji (CC BY-SA 4.0) + Twemoji (CC BY 4.0), flat colour
# Idempotent: skips files that already exist. Tolerates missing names.
set -u
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/corpus/src"
TMP="${TMPDIR:-/tmp}/vectorize-fetch"
mkdir -p "$SRC/bw" "$SRC/color" "$TMP"

SIMPLE=(github google apple microsoft amazon netflix spotify x facebook instagram youtube linkedin
reddit discord slack telegram whatsapp tiktok snapchat pinterest twitch steam playstation xbox
nintendo android ubuntu debian linux archlinux fedora docker kubernetes rust python javascript
typescript react vuedotjs angular svelte nodedotjs deno go ruby php swift kotlin html5 css git
gitlab bitbucket npm yarn webpack vite vercel netlify cloudflare nginx postgresql mysql mongodb
redis sqlite firebase supabase stripe paypal visa mastercard bitcoin ethereum tesla bmw mercedes
toyota nike adidas starbucks mcdonalds cocacola wikipedia mozilla firefox chromium figma blender
unity godotengine notion obsidian)
FA=(house user gear magnifying-glass heart star bell envelope camera image music film book bookmark
calendar clock cloud bolt fire leaf tree paw bug car plane truck bicycle rocket anchor flag gift key
lock wrench hammer scissors pen trash thumbs-up face-smile)
EMOJI=(1F600 1F60D 1F602 1F622 1F621 1F914 1F47B 1F480 1F436 1F431 1F98A 1F43C 1F981 1F438 1F41D 1F98B
1F33B 1F334 1F34E 1F34C 1F355 1F354 1F370 1F680 1F697 1F6B2 1F3E0 1F3F0 1F308 2600 1F319 2B50 26A1
1F525 1F4A7 1F3B8 1F3AE 1F4F1 1F4BB 1F4A1 1F512 1F511 2764 1F389 1F3AF 26BD 1F3C0 1F451 1F48E 1F9E9)

echo "== Simple Icons"
if [ ! -d "$TMP/simple-icons/package" ]; then
  mkdir -p "$TMP/simple-icons" && (cd "$TMP/simple-icons" && npm pack simple-icons --silent >/dev/null 2>&1 && tar xzf simple-icons-*.tgz)
fi
for n in "${SIMPLE[@]}"; do
  f="$TMP/simple-icons/package/icons/$n.svg"
  [ -f "$f" ] && cp -n "$f" "$SRC/bw/si-$n.svg" || echo "  missing simple-icons/$n"
done

echo "== Font Awesome Free"
if [ ! -d "$TMP/fa/package" ]; then
  mkdir -p "$TMP/fa" && (cd "$TMP/fa" && npm pack @fortawesome/fontawesome-free --silent >/dev/null 2>&1 && tar xzf fortawesome-fontawesome-free-*.tgz)
fi
for n in "${FA[@]}"; do
  f="$TMP/fa/package/svgs/solid/$n.svg"
  [ -f "$f" ] && cp -n "$f" "$SRC/bw/fa-$n.svg" || echo "  missing fa/$n"
done

echo "== OpenMoji"
for c in "${EMOJI[@]}"; do
  out="$SRC/color/om-$c.svg"
  [ -f "$out" ] && continue
  curl -sfL "https://raw.githubusercontent.com/hfg-gmuend/openmoji/master/color/svg/$c.svg" -o "$out" || { rm -f "$out"; echo "  missing openmoji/$c"; }
done

echo "== Twemoji (first 30)"
for c in "${EMOJI[@]:0:30}"; do
  lc=$(echo "$c" | tr 'A-F' 'a-f')
  out="$SRC/color/tw-$lc.svg"
  [ -f "$out" ] && continue
  curl -sfL "https://cdn.jsdelivr.net/gh/twitter/twemoji@14.0.2/assets/svg/$lc.svg" -o "$out" || { rm -f "$out"; echo "  missing twemoji/$lc"; }
done

echo "bw: $(ls "$SRC/bw" | wc -l) files, color: $(ls "$SRC/color" | wc -l) files"
cat > "$SRC/LICENSES.md" <<'L'
Corpus sources and licenses (benchmark use only, not redistributed):
- Simple Icons — CC0 1.0 — https://simpleicons.org
- Font Awesome Free (solid) — CC BY 4.0 — https://fontawesome.com/license/free
- OpenMoji — CC BY-SA 4.0 — https://openmoji.org
- Twemoji — CC BY 4.0 — https://github.com/twitter/twemoji
- synthetic/ — generated by `bench build-corpus`, public domain
L
